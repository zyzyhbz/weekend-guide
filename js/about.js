<section class="doc">
  <h2>⚙️ 推荐算法怎么做的</h2>
  <p>没有用机器学习，用的是<strong>可解释的加权打分 + 采样</strong>。对附加题来说，<b>能讲清楚为什么推荐它</b>比模型复杂度更重要。</p>
  <h3>Step 1 · 硬约束过滤（不满足直接出局）</h3>
  <ul>
    <li>时长塞不进时间窗（"傍晚夜场 4h"容不下 9h 的徒步）</li>
    <li>极端天气下的纯户外活动（安全优先，不做"建议自行判断"这种甩锅）</li>
    <li>最低花费超预算 1.5 倍</li>
    <li>单程距离超出用户可接受范围</li>
    <li>用户已排除</li>
  </ul>
  <h3>Step 2 · 九维加权打分</h3>
  <p>偏好命中（主权重，Jaccard 式匹配）、天气适配（活动自带敏感度模型）、预算契合、人数契合、时间窗契合、通勤成本、口碑质量、体力匹配、稀缺性偏好。每一维都会往 <code>reasons[]</code> 或 <code>warnings[]</code> 里写一句话。</p>
  <h3>Step 3 · 软最大化采样（Softmax Sampling）</h3>
  <p>分数转概率，按温度参数抽样。<strong>同样的输入点两次，不会给完全一样的结果</strong>——因为"周末去哪"本来就没有唯一正解，过度确定反而让人怀疑推荐质量。</p>
  <h3>Step 4 · MMR 多样性重排</h3>
  <p>用标签 Jaccard 相似度 + 同类目/同商圈惩罚，保证 3 个方案<b>性格不同</b>（不会三个都是美术馆）。这是"给选项"和"给真选项"的区别。</p>
  <h3>Step 5 · 可解释性输出</h3>
  <p>每个方案都带：匹配理由（绿标）、风险提示（黄标）、时间轴、账单拆解、出发清单。<strong>推荐系统最大的问题是"黑箱"，所以我把推理过程直接摆在界面上。</strong></p>
</section>

